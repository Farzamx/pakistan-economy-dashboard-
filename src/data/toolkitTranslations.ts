// Pre-translated Roman Urdu cache for every InfoTooltip / TERMINOLOGY entry.
//
// Goal: 100% cache hit rate for existing toolkit content — InfoTooltip checks
// this file before ever calling /api/assistant/translate. AI translation is
// only a fallback for content that isn't in this map yet.
//
// `key` must exactly match the TERMINOLOGY key (= InfoTooltip's termKey prop).
// `english` is the literal text InfoTooltip would otherwise send to the AI
// translator (same "Kya hai? / Kyun zaroori hai? / Kaise samjhein?" format),
// so a cache lookup is a simple equality check against what's already cached.
// `romanUrdu` is the full human-quality translation in that same format —
// headings AND body are both Roman Urdu, never a mix.

export interface ToolkitTranslation {
  key: string;
  english: string;
  romanUrdu: string;
}

function buildEnglish(what: string, why: string, how: string[]): string {
  return [
    `Kya hai?\n${what}`,
    `Kyun zaroori hai?\n${why}`,
    `Kaise samjhein?\n${how.map((b) => `• ${b}`).join("\n")}`,
  ].join("\n\n");
}

function buildUrdu(what: string, why: string, how: string[]): string {
  return [
    `Kya hai?\n${what}`,
    `Kyun zaroori hai?\n${why}`,
    `Kaise samjhein?\n${how.map((b) => `• ${b}`).join("\n")}`,
  ].join("\n\n");
}

